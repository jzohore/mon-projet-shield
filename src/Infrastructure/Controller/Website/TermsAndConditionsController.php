<?php

declare(strict_types=1);

namespace App\Infrastructure\Controller\Website;

use Symfony\Component\HttpFoundation\Response;
use Symfony\Component\HttpKernel\Attribute\AsController;
use Symfony\Component\Routing\Attribute\Route;
use Twig\Environment;
use Twig\Error\LoaderError;
use Twig\Error\RuntimeError;
use Twig\Error\SyntaxError;

#[AsController]
#[Route(path: '/terms-and-conditions', name: 'website_terms_and_conditions')]
final readonly class TermsAndConditionsController
{
    /**
     * @throws RuntimeError
     * @throws SyntaxError
     * @throws LoaderError
     */
    public function __invoke(
        Environment $twig,
    ): Response {
        return new Response(
            $twig->render('@website/terms_and_conditions.html.twig')
        );
    }
}
